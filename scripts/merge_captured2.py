def main():
    cand = json.load(open(SRC, encoding="utf-8"))["translations"]
    keys = list(cand.keys())
    if len(keys) != len(TR):
        import sys
        sys.exit(f"candidate {len(keys)} != translation {len(TR)}")
    maind = json.load(open(MAIN, encoding="utf-8"))
    trans = maind.setdefault("translations", {})
    added = 0
    for i, k in enumerate(keys):
        v = TR[i]
        if not v or v == k or k in trans:
            continue
        trans[k] = v
        added += 1
    json.dump(maind, open(MAIN, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    shutil.copyfile(MAIN, os.path.join(ROOT, "build", "translations", "dictionary_zh.json"))
    print(f"added {added}; dictionary now {len(trans)} entries")


if __name__ == "__main__":
    main()
